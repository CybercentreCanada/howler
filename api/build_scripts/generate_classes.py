"""Generate UI entity declarations from the public, offline model JSON Schema."""

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

OUTPUT_DIR = Path(__file__).resolve().parents[2] / "ui/src/models/entities/generated"
HEADER = "// @generated by api/build_scripts/generate_classes.py. Do not edit."
PRIMITIVES = {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}
IDENTIFIER = re.compile(r"[A-Za-z_$][\w$]*", re.ASCII)

# Preserve established UI imports and avoid reusing an old module name for an
# unrelated type. Other exports follow the definition, never its traversal path.
EXPORT_NAMES = {
    "AssemblyLine": "Assemblyline",
    "CaseEnrichment": "Enrichments",
    "CaseItem": "Item",
    "CaseRule": "Rule",
    "CaseTask": "Task",
    "Label": "Labels",
    "HowlerData": "Howler",
    "EventData": "EventHowler",
    "Rule": "ECSRule",
    "Enrichments": "ThreatEnrichment",
    "Tactic": "ThreatTactic",
    "analytic__Comment": "Comment",
    "howler_data__Comment": "HowlerComment",
    "elf__Header": "Header",
    "header__Header": "Outline",
    "file__File": "HitFile",
    "email__File": "File",
    "aws__Organization": "Organization",
    "organization__Organization": "HitOrganization",
    "client__Client": "Source",
    "tls__Client": "Client",
}


def export_name(key: str) -> str:
    """Use the module to disambiguate Pydantic's qualified definition keys."""
    parts = key.split("__")[-2:]
    if name := EXPORT_NAMES.get("__".join(parts)):
        return name
    if len(parts) == 2 and parts[0].casefold() == parts[1].casefold():
        parts = parts[1:]
    return "".join(
        word.capitalize() if word.isupper() else word[:1].upper() + word[1:] for word in "_".join(parts).split("_")
    )


def literal(value: Any) -> str:
    """Render JSON scalars with TypeScript string escaping."""
    if isinstance(value, str):
        return "'" + json.dumps(value)[1:-1].replace('\\"', '"').replace("'", "\\'") + "'"
    if value is None or isinstance(value, (int, float, bool)):
        return json.dumps(value, allow_nan=False)
    raise ValueError(f"Unsupported non-scalar literal: {value!r}")


def ref_key(ref: str) -> str:
    """Only references to local, named schema definitions are part of the contract."""
    prefix = "#/$defs/"
    if not ref.startswith(prefix) or "/" in ref[len(prefix) :]:
        raise ValueError(f"Expected a local definition reference, got {ref!r}")
    return ref[len(prefix) :].replace("~1", "/").replace("~0", "~")


def render_entities(schema: dict[str, Any]) -> dict[str, str]:
    """Emit each reachable definition once, including recursive and shared refs."""
    defs = schema["$defs"]
    roots: dict[str, list[str]] = defaultdict(list)
    for index, node in schema["properties"].items():
        roots[ref_key(node["$ref"])].append("UserUser" if index == "user" else export_name(index))
    names = {key: export_name(key) for key in defs}
    for key, exports in roots.items():
        # Prefer the model's own public name; other roots re-export the same type.
        exports.sort(key=lambda name: (name != names.get(key), name))
        names[key] = exports[0]
    pending = set(roots)
    rendered = set()
    used_names = {"apitype"}  # The live config generator owns this module (also on case-insensitive filesystems).
    files: dict[str, str] = {}

    def add_file(name: str, declaration: str) -> None:
        if not IDENTIFIER.fullmatch(name) or name.casefold() in used_names:
            raise ValueError(f"Invalid or conflicting export name {name!r}")
        used_names.add(name.casefold())
        files[f"{name}.d.ts"] = f"{HEADER}\n{declaration}\n"

    while pending:
        key = pending.pop()
        if key not in defs:
            raise ValueError(f"Missing schema definition {key!r}")
        name = names[key]
        refs: set[str] = set()
        node = defs[key]
        if isinstance(node, dict) and node.get("type") == "object" and "properties" in node:
            members = object_members(node, names, refs)
            body = f"export interface {name} {{\n" + "".join(f"  {member};\n" for member in members) + "}"
        else:
            body = f"export type {name} = {type_expression(node, names, refs)};"
        imports = sorted({names[ref] for ref in refs - {key}}, key=lambda s: (s.casefold(), s))
        declarations = [f"import type {{ {other} }} from './{other}';" for other in imports]
        prefix = "\n".join(declarations) + "\n\n" if declarations else ""
        add_file(name, prefix + body)
        rendered.add(key)
        pending.update(refs - rendered)
    for target, *aliases in roots.values():
        for alias in aliases:
            add_file(alias, f"export type {{ {target} as {alias} }} from './{target}';")
    return files


def object_members(node: dict, names: dict[str, str], refs: set[str]) -> list[str]:
    """Property names are wire aliases. Requiredness and nullability are independent."""
    members = []
    for key, prop in sorted(node.get("properties", {}).items()):
        name = key if IDENTIFIER.fullmatch(key) else literal(key)
        optional = "" if key in node.get("required", ()) else "?"
        members.append(f"{name}{optional}: {type_expression(prop, names, refs)}")
    additional = node.get("additionalProperties", not members)
    if additional is not False:
        members.append(f"[index: string]: {type_expression(additional, names, refs)}")
    return members


def type_expression(node: Any, names: dict[str, str], refs: set[str]) -> str:  # noqa: C901
    """Translate the JSON Schema vocabulary emitted by the public exporter."""
    if isinstance(node, bool):
        return "unknown" if node else "never"
    if "not" in node:
        if node["not"] != {"type": "null"}:
            raise ValueError(f"Unsupported entity negation: {node['not']!r}")
        inner = type_expression({key: value for key, value in node.items() if key != "not"}, names, refs)
        if inner == "unknown":
            return type_expression({"type": ["boolean", "number", "string", "array", "object"]}, names, refs)
        return f"NonNullable<{inner}>"
    if "$ref" in node:
        key = ref_key(node["$ref"])
        if key not in names:
            raise ValueError(f"Missing schema definition {key!r}")
        refs.add(key)
        return names[key]
    if "const" in node:
        return literal(node["const"])
    if "enum" in node:
        return " | ".join(map(literal, node["enum"])) or "never"
    for keyword in ("anyOf", "oneOf"):
        if keyword in node:
            return (
                " | ".join(dict.fromkeys(type_expression(option, names, refs) for option in node[keyword])) or "never"
            )
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(type_expression({**node, "type": t}, names, refs) for t in kind)
    if kind == "array":
        item = type_expression(node.get("items", True), names, refs)
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        members = object_members(node, names, refs)
        return "{ " + "; ".join(members) + " }" if members else "Record<string, never>"
    if kind in PRIMITIVES:
        return PRIMITIVES[kind]
    if kind is None and not (node.keys() & {"allOf", "not", "if", "properties"}):
        return "unknown"  # An unconstrained value (possibly annotated with a title/description).
    raise ValueError(f"Unsupported entity schema: {node!r}")


def _is_entity_file(path: Path) -> bool:
    if path.name.casefold() == "apitype.d.ts" or path.is_symlink() or not path.is_file():
        return False
    with path.open("rb") as file:
        return file.readline(len(HEADER) + 2).rstrip(b"\r\n") == HEADER.encode()


def sync_output(output_dir: Path, expected: dict[str, str], *, check: bool) -> bool:
    """Preflight ownership for the entire batch before writing or deleting anything."""
    entries = output_dir.iterdir() if output_dir.exists() else ()
    existing = {p.name: p for p in entries if p.name.casefold().endswith(".d.ts")}
    owned = {name: path for name, path in existing.items() if _is_entity_file(path)}
    targets = {name.casefold() for name in expected}
    collisions = sorted(name for name in existing.keys() - owned.keys() if name.casefold() in targets)
    if collisions:
        for name in collisions:
            sys.stderr.write(f"Unowned declaration: {output_dir / name}\n")
        return False
    stale = sorted(owned.keys() - expected.keys())
    changed = sorted(
        name for name, text in expected.items() if name not in owned or owned[name].read_bytes() != text.encode()
    )
    if check:
        for name in changed:
            sys.stderr.write(f"{'Changed' if name in existing else 'Missing'}: {name}\n")
        for name in stale:
            sys.stderr.write(f"Stale: {name}\n")
        return not (changed or stale)
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in stale:
        owned[name].unlink()
    for name in changed:
        (output_dir / name).write_bytes(expected[name].encode())
    return True


def main() -> int:
    """Generate the checked-in declarations, or check them without writing."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Report missing, changed or stale declarations without writing"
    )
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args()
    from build_scripts.model_json_schema import entity_schema

    return 0 if sync_output(args.output_dir, render_entities(entity_schema()), check=args.check) else 1


if __name__ == "__main__":
    sys.exit(main())
